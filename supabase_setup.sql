-- Supabase SQL Editor bölümünde bir kez çalıştır.
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Diğer',
  youtube_url text,
  video_url text,
  thumbnail text,
  published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.videos enable row level security;

drop policy if exists "Herkes yayınlanan videoları görebilir" on public.videos;
create policy "Herkes yayınlanan videoları görebilir"
on public.videos for select
using (published = true);

drop policy if exists "Giriş yapan yönetici video ekleyebilir" on public.videos;
create policy "Giriş yapan yönetici video ekleyebilir"
on public.videos for insert to authenticated
with check (auth.uid() = created_by);

drop policy if exists "Yönetici kendi videolarını silebilir" on public.videos;
create policy "Yönetici kendi videolarını silebilir"
on public.videos for delete to authenticated
using (auth.uid() = created_by);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('videos', 'videos', true, 524288000, array['video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public = true, file_size_limit = 524288000,
allowed_mime_types = array['video/mp4','video/webm','video/quicktime'];

drop policy if exists "Herkes video dosyalarını izleyebilir" on storage.objects;
create policy "Herkes video dosyalarını izleyebilir"
on storage.objects for select
using (bucket_id = 'videos');

drop policy if exists "Giriş yapanlar video yükleyebilir" on storage.objects;
create policy "Giriş yapanlar video yükleyebilir"
on storage.objects for insert to authenticated
with check (bucket_id = 'videos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Kullanıcı kendi video dosyasını silebilir" on storage.objects;
create policy "Kullanıcı kendi video dosyasını silebilir"
on storage.objects for delete to authenticated
using (bucket_id = 'videos' and (storage.foldername(name))[1] = auth.uid()::text);
